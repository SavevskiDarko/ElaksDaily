#!/usr/bin/env node
// What the code expects the database to contain.
//
// This is NOT the schema — only `supabase db pull` can produce that (see
// supabase/migrations/README.md). It is the checklist to hold a pull against:
// every table, view, function and column the app and the edge functions
// actually name. If the dump is missing something listed here, the dump is
// incomplete.
//
//   node scripts/schema-inventory.mjs > supabase/EXPECTED.md
import { readFileSync, readdirSync, existsSync } from "node:fs";

const SOURCES = ["index.html"];
for (const dir of existsSync("supabase/functions") ? readdirSync("supabase/functions") : []) {
  const f = `supabase/functions/${dir}/index.ts`;
  if (existsSync(f)) SOURCES.push(f);
}

const tables = new Map();   // name -> { columns:Set, sources:Set }
const rpcs = new Map();     // name -> Set of sources

// From `at`, consume as many `.method(...)` calls as follow, with balanced
// parens, and return just those. Stops at the first thing that is not part of
// the chain, so one statement's columns never leak into the next table's row.
function chainAfter(src, at) {
  let i = at;
  for (;;) {
    const m = /^\s*\.[a-zA-Z_$][\w$]*\(/.exec(src.slice(i, i + 80));
    if (!m) break;
    let depth = 0, j = i + m[0].length - 1;
    for (; j < src.length; j++) {
      const c = src[j];
      if (c === '"' || c === "'" || c === "`") {           // skip a string
        const quote = c;
        for (j++; j < src.length && src[j] !== quote; j++) if (src[j] === "\\") j++;
        continue;
      }
      if (c === "(") depth++;
      else if (c === ")" && --depth === 0) break;
    }
    if (j >= src.length) break;
    i = j + 1;
  }
  return src.slice(at, i);
}

const touch = (name, src) => {
  if (!tables.has(name)) tables.set(name, { columns: new Set(), sources: new Set() });
  const t = tables.get(name);
  t.sources.add(src);
  return t;
};

for (const file of SOURCES) {
  const src = readFileSync(file, "utf8");

  // .from("x") followed by its own chained calls, and nothing after them —
  // a fixed lookahead window would attribute the next statement's columns to
  // this table.
  for (const m of src.matchAll(/\.from\("([a-z_]+)"\)/g)) {
    const t = touch(m[1], file);
    const tail = chainAfter(src, m.index + m[0].length);

    // .select("a, b, joined(name)")
    const sel = tail.match(/\.select\(\s*"([^"]*)"/);
    if (sel) {
      for (const col of sel[1].split(",")) {
        const name = col.trim().replace(/\([^)]*\)/, "").trim();
        if (name && name !== "*" && /^[a-z_][a-z0-9_]*$/.test(name)) t.columns.add(name);
      }
      // an embedded resource, e.g. clients(name), is a foreign table
      for (const emb of sel[1].matchAll(/([a-z_]+)\s*\(/g)) touch(emb[1], file);
    }
    // filters and ordering name real columns
    for (const f of tail.matchAll(/\.(?:eq|neq|gt|gte|lt|lte|like|ilike|is|in)\(\s*"([a-z_]+)"/g)) t.columns.add(f[1]);
    for (const f of tail.matchAll(/\.order\(\s*"([a-z_]+)"/g)) t.columns.add(f[1]);
    for (const f of tail.matchAll(/onConflict:\s*"([a-z_]+)"/g)) t.columns.add(f[1]);
  }

  for (const m of src.matchAll(/\.rpc\(\s*"([a-z_]+)"/g)) {
    if (!rpcs.has(m[1])) rpcs.set(m[1], new Set());
    rpcs.get(m[1]).add(file);
  }
}

const VIEWS = new Set(["article_stock", "elaks_cash_total", "apt_cash_total",
  "team_members", "entry_authors"]);
const names = [...tables.keys()].sort();
const short = (f) => f.replace("supabase/functions/", "").replace("/index.ts", "");

const out = [];
out.push("# What the database must contain");
out.push("");
out.push("Generated by `node scripts/schema-inventory.mjs`. Do not edit by hand.");
out.push("");
out.push("This lists every table, view and function the code names, and the columns");
out.push("it names explicitly. It is a **checklist, not a schema** — it cannot show");
out.push("types, defaults, constraints, indexes or row-level security, and a table");
out.push("read with `select(\"*\")` shows no columns at all here. The real schema comes");
out.push("from `supabase db pull`; see `supabase/migrations/README.md`.");
out.push("");
out.push(`## Tables and views — ${names.length}`);
out.push("");
out.push("| relation | kind | named by | columns named in code |");
out.push("| --- | --- | --- | --- |");
for (const n of names) {
  const t = tables.get(n);
  // select("*, clients(name)") embeds a foreign table; it is a relation in its
  // own right, already listed, and not a column of this one
  const cols = [...t.columns].filter((c) => !tables.has(c)).sort();
  out.push(`| \`${n}\` | ${VIEWS.has(n) ? "view" : "table"} | ${[...t.sources].map(short).map((s) => `\`${s}\``).join(", ")} | ${cols.length ? cols.map((c) => `\`${c}\``).join(" ") : "_only `*`_"} |`);
}
out.push("");
out.push(`## Functions called with \`rpc()\` — ${rpcs.size}`);
out.push("");
if (rpcs.size) {
  for (const [n, srcs] of [...rpcs].sort()) {
    out.push(`- \`${n}()\` — called from ${[...srcs].map(short).map((s) => `\`${s}\``).join(", ")}`);
  }
} else {
  out.push("_none_");
}
out.push("");
out.push("## Also required, and invisible to this script");
out.push("");
out.push("- **Row-level security policies on every table above.** The app decides what");
out.push("  each person sees in the browser, from `user_roles`; that is a convenience,");
out.push("  not a boundary. Anyone signed in holds the anon key and can call the REST");
out.push("  API directly, so the policies are the only real enforcement.");
out.push("- **`user_roles` must not be self-editable.** The app inserts a row on first");
out.push("  sign-in and the owner edits rows from the Team screen. An employee must not");
out.push("  be able to set their own `role` to `owner`.");
out.push("- **`secrets`** holds the Anthropic API key and must have no select policy —");
out.push("  only `read-doc`, running as the service role, may read it. Written through");
out.push("  `set_secret()` / `clear_secret()`.");
out.push("- **Unique constraints on `offers.number` and `invoices.number`.** The app");
out.push("  reads the highest and adds one; without the constraint two devices can");
out.push("  produce two documents with the same number.");
out.push("- **Storage buckets**, if photos are ever moved out of the `*_photos` and");
out.push("  `*_images` tables.");
out.push("");
console.log(out.join("\n"));
